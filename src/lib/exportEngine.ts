import * as XLSX from 'xlsx';
import {
  ClarificationQuestion,
  CostSheetFinding,
  CrossDocConflict,
  ExtractedRequirement,
  SubmissionChecklistItem,
  TenderWorkspace,
} from '../types';

export function exportFullTenderToExcel(
  workspace: TenderWorkspace,
  requirements: ExtractedRequirement[],
  costFindings: CostSheetFinding[],
  conflicts: CrossDocConflict[],
  clarifications: ClarificationQuestion[],
  checklist: SubmissionChecklistItem[]
): void {
  const wb = XLSX.utils.book_new();

  // 1. Executive Summary Sheet
  const summaryAoa = [
    ['TENDER & RFP INTELLIGENCE AUDIT REPORT'],
    ['Generated by BidIntel Engine', '', 'Date:', new Date().toISOString().split('T')[0]],
    [''],
    ['Tender Name:', workspace.name],
    ['Client:', workspace.client],
    ['Geography / Region:', workspace.geography],
    ['Submission Deadline:', workspace.bidDeadline],
    ['Internal Lead:', workspace.internalOwner],
    ['Estimated Bid Value:', `${workspace.currency} ${workspace.estimatedValue.toLocaleString()}`],
    ['Audit Status:', workspace.status],
    [''],
    ['AUDIT SUMMARY METRICS', 'COUNT'],
    ['Total Extracted Requirements', requirements.length],
    ['Critical / High Risk Requirements', requirements.filter((r) => r.riskLevel === 'Critical' || r.riskLevel === 'High').length],
    ['Cost Sheet Audit Discrepancies', costFindings.length],
    ['Critical Cost Formula & Math Errors', costFindings.filter((c) => c.severity === 'Critical').length],
    ['Cross-Document Contractual Conflicts', conflicts.length],
    ['Clarification Questions Generated', clarifications.length],
    ['Mandatory Pre-Bid Questions', clarifications.filter((q) => q.isMandatoryBeforeSubmission).length],
    ['Submission Checklist Completed', `${checklist.filter((c) => c.status === 'Complete').length} of ${checklist.length}`],
  ];
  const wsSummary = XLSX.utils.aoa_to_sheet(summaryAoa);
  wsSummary['!cols'] = [{ wch: 35 }, { wch: 30 }, { wch: 15 }, { wch: 20 }];
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Executive_Summary');

  // 2. Master Requirements Register
  const reqHeaders = [
    'Req ID',
    'Category',
    'Risk Level',
    'Mandatory/Optional',
    'Source File',
    'Location / Page / Cell',
    'Original Requirement Text',
    'AI Legal & Commercial Interpretation',
    'Clarification Required',
    'Suggested Question',
    'Assigned Owner',
    'Review Status',
    'Reviewer Comments',
    'Citation Reference',
  ];
  const reqRows = requirements.map((r) => [
    r.id,
    r.requirementCategory,
    r.riskLevel,
    r.classification,
    r.sourceFileName,
    `${r.pageNumber} (${r.tableRowCellRef})`,
    r.originalText,
    r.aiInterpretation,
    r.clarificationRequired ? 'YES' : 'NO',
    r.suggestedClarificationQuestion || '-',
    r.responsibleOwner,
    r.status,
    r.reviewerComments,
    r.evidenceCitation,
  ]);
  const wsReq = XLSX.utils.aoa_to_sheet([reqHeaders, ...reqRows]);
  wsReq['!cols'] = [
    { wch: 12 },
    { wch: 24 },
    { wch: 12 },
    { wch: 18 },
    { wch: 28 },
    { wch: 22 },
    { wch: 45 },
    { wch: 40 },
    { wch: 14 },
    { wch: 35 },
    { wch: 20 },
    { wch: 14 },
    { wch: 30 },
    { wch: 30 },
  ];
  XLSX.utils.book_append_sheet(wb, wsReq, 'Requirements_Register');

  // 3. Cost Sheet Audit Register
  const costHeaders = [
    'Finding ID',
    'Severity',
    'Check Category',
    'File Name',
    'Worksheet',
    'Cell / Range',
    'Observed Value / Formula',
    'Expected Rule / Calculation',
    'Variance / Diff',
    'Detailed Explanation',
    'Recommended Action',
    'Reviewer Status',
    'Assigned Owner',
    'Evidence Reference',
  ];
  const costRows = costFindings.map((c) => [
    c.id,
    c.severity,
    c.checkCategory,
    c.fileName,
    c.worksheet,
    c.cellOrRange,
    c.observedValueOrFormula,
    c.expectedCalculationOrRule,
    c.difference !== undefined ? String(c.difference) : '-',
    c.explanation,
    c.recommendedAction,
    c.reviewerStatus,
    c.assignedOwner || 'Unassigned',
    c.evidenceReference,
  ]);
  const wsCost = XLSX.utils.aoa_to_sheet([costHeaders, ...costRows]);
  wsCost['!cols'] = [
    { wch: 14 },
    { wch: 12 },
    { wch: 24 },
    { wch: 28 },
    { wch: 20 },
    { wch: 14 },
    { wch: 24 },
    { wch: 35 },
    { wch: 16 },
    { wch: 45 },
    { wch: 40 },
    { wch: 16 },
    { wch: 20 },
    { wch: 30 },
  ];
  XLSX.utils.book_append_sheet(wb, wsCost, 'Cost_Sheet_Audit');

  // 4. Cross-Document Conflicts
  const conflictHeaders = [
    'Conflict ID',
    'Severity',
    'Confidence',
    'Issue Title',
    'Source A Document',
    'Source A Reference',
    'Source A Extracted Text',
    'Source B Document',
    'Source B Reference',
    'Source B Extracted Text',
    'Why Conflict Exists / Impact',
    'Precedence Rule Applied',
    'Suggested Clarification Question',
    'Human Review Status',
    'Reviewer Notes',
  ];
  const conflictRows = conflicts.map((c) => [
    c.id,
    c.severity,
    c.confidence,
    c.issueTitle,
    c.sourceA.fileName,
    c.sourceA.exactReference,
    c.sourceA.extractedTextOrValue,
    c.sourceB.fileName,
    c.sourceB.exactReference,
    c.sourceB.extractedTextOrValue,
    c.conflictReason,
    c.precedenceApplied || 'Not stated in tender',
    c.suggestedClarificationQuestion,
    c.humanReviewStatus,
    c.reviewerNotes || '-',
  ]);
  const wsConflicts = XLSX.utils.aoa_to_sheet([conflictHeaders, ...conflictRows]);
  wsConflicts['!cols'] = [
    { wch: 14 },
    { wch: 12 },
    { wch: 12 },
    { wch: 30 },
    { wch: 26 },
    { wch: 22 },
    { wch: 35 },
    { wch: 26 },
    { wch: 22 },
    { wch: 35 },
    { wch: 40 },
    { wch: 25 },
    { wch: 35 },
    { wch: 18 },
    { wch: 25 },
  ];
  XLSX.utils.book_append_sheet(wb, wsConflicts, 'Cross_Doc_Conflicts');

  // 5. Clarification Questions
  const cqHeaders = [
    'Question ID',
    'Priority',
    'Category',
    'Mandatory Before Bid',
    'Clarification Question Text',
    'Business & Commercial Rationale',
    'Source Document & Exact Ref',
    'Related Finding / Conflict',
    'Suggested Recipient',
    'Status',
    'Reviewer Comments',
  ];
  const cqRows = clarifications.map((q) => [
    q.id,
    q.priority,
    q.category,
    q.isMandatoryBeforeSubmission ? 'YES - CRITICAL' : 'Optional',
    q.questionText,
    q.businessReason,
    `${q.sourceDocument} [${q.exactReference}]`,
    q.relevantRequirementOrConflict,
    q.suggestedRecipient,
    q.status,
    q.reviewerComments || '-',
  ]);
  const wsCq = XLSX.utils.aoa_to_sheet([cqHeaders, ...cqRows]);
  wsCq['!cols'] = [
    { wch: 12 },
    { wch: 12 },
    { wch: 16 },
    { wch: 18 },
    { wch: 45 },
    { wch: 35 },
    { wch: 30 },
    { wch: 22 },
    { wch: 24 },
    { wch: 16 },
    { wch: 25 },
  ];
  XLSX.utils.book_append_sheet(wb, wsCq, 'Clarification_Questions');

  // 6. Submission Readiness Checklist
  const chkHeaders = [
    'Item ID',
    'Submission Section',
    'Checklist Title',
    'Description',
    'Status',
    'Assigned Owner',
    'Target Due Date',
    'Evidence Reference / Document',
    'Progress Notes',
  ];
  const chkRows = checklist.map((k) => [
    k.id,
    k.category,
    k.title,
    k.description,
    k.status,
    k.owner,
    k.dueDate,
    k.evidenceReference,
    k.notes,
  ]);
  const wsChk = XLSX.utils.aoa_to_sheet([chkHeaders, ...chkRows]);
  wsChk['!cols'] = [
    { wch: 12 },
    { wch: 24 },
    { wch: 28 },
    { wch: 35 },
    { wch: 16 },
    { wch: 22 },
    { wch: 14 },
    { wch: 28 },
    { wch: 30 },
  ];
  XLSX.utils.book_append_sheet(wb, wsChk, 'Submission_Checklist');

  // Trigger browser download
  const safeName = workspace.name.replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 30);
  XLSX.writeFile(wb, `BidIntel_Audit_${safeName}_${Date.now()}.xlsx`);
}

export function exportToCsv(filename: string, headers: string[], rows: (string | number)[][]): void {
  const csvContent = [
    headers.map((h) => `"${String(h).replace(/"/g, '""')}"`).join(','),
    ...rows.map((row) =>
      row.map((cell) => `"${String(cell ?? '').replace(/"/g, '""')}"`).join(',')
    ),
  ].join('\r\n');

  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
